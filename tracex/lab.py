"""Evaluation lab: every scenario, baseline (raw times) vs clock-aware, measured against ground truth."""
from pathlib import Path

import pandas as pd

from . import mitigation
from .attack import coverage, map_techniques
from .evaluation import evaluate
from .explain import gaps
from .parsers import load_dataset
from .pipeline import analyse


def _fragmentation(found, expected):
    if found == expected:
        return "correct"
    if expected and found > expected:
        return f"split into {found}"
    if found < expected:
        return "missed" if found == 0 else "merged"
    return f"{found} false incident(s)"


def run(data_dir):
    rows = []
    for folder in sorted(p for p in Path(data_dir).iterdir() if (p / "ground_truth.json").exists()):
        events, info = load_dataset(folder)
        truth = info["ground_truth"]
        for aware in (False, True):
            a = analyse(events, clock_aware=aware)
            r = evaluate(a.incidents, truth)
            refs = set(a.incidents[0].chain["raw_ref"]) if a.incidents else set()
            cov = coverage(map_techniques(a.view, a.detections, refs if a.incidents else None),
                           truth.get("expected_techniques", {})) if a.incidents else None
            found_gaps = sorted(k for k, _ in gaps(a, info))
            lock = next(p for p in mitigation.validate(a.view, a.incidents) if p.name == "Account lockout")
            rows.append({
                "scenario": folder.name, "mode": "clock-aware" if aware else "baseline",
                "expected incidents": truth.get("expected_incidents"), "incidents": len(a.incidents),
                "fragmentation": _fragmentation(len(a.incidents), truth.get("expected_incidents", 0)),
                "attack events": r["ground_truth_events"], "linked": r["correctly_linked"],
                "missed": len(r["missed"]), "false positives": len(r["false_positives"]),
                "recall": r["recall"], "precision": r["precision"],
                "techniques": f"{len(cov['matched'])}/{len(cov['expected'])}" if cov else "—",
                "gaps found": ", ".join(found_gaps) or "none",
                "gaps expected": ", ".join(sorted(truth.get("expected_gaps", []))) or "none",
                "clock": ", ".join(f"{f.host}: {f.status}" for f in a.clock) or "no host log",
                "lockout": lock.verdict, "legit blocked": len(lock.legit_blocked),
            })
    return pd.DataFrame(rows)


def to_markdown(df):
    pct = lambda v: "—" if v is None or pd.isna(v) else f"{v:.0%}"
    lines = ["# TraceX AI — measured test results", "",
             "Generated by `python scripts/run_evaluation.py` from the synthetic scenarios and their ground truth. "
             "All numbers are measured; nothing is estimated by hand. Scenarios were designed by the team, so "
             "these results show the method works as intended on known cases, not real-world accuracy.", "",
             "## Reconstruction (baseline = raw timestamps, clock-aware = with clock-skew correction)", "",
             "| Scenario | Mode | Incidents (expected) | Fragmentation | Linked / attack events | Missed | False pos. | Recall | Precision |",
             "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for _, r in df.iterrows():
        lines.append(f"| {r['scenario']} | {r['mode']} | {r['incidents']} ({r['expected incidents']}) | {r['fragmentation']} | "
                     f"{r['linked']} / {r['attack events']} | {r['missed']} | {r['false positives']} | {pct(r['recall'])} | {pct(r['precision'])} |")
    aware = df[df["mode"] == "clock-aware"]
    lines += ["", "## Evidence reliability, ATT&CK and mitigation (clock-aware mode)", "",
              "| Scenario | Clock check | Gaps found | Gaps expected | ATT&CK expected found | Lockout policy | Legit logins blocked |",
              "| --- | --- | --- | --- | --- | --- | --- |"]
    for _, r in aware.iterrows():
        lines.append(f"| {r['scenario']} | {r['clock']} | {r['gaps found']} | {r['gaps expected']} | {r['techniques']} | "
                     f"{r['lockout']} | {r['legit blocked']} |")
    lines += ["", "## Known limitations", "",
              "- Rules and thresholds were written for these scenarios; slow attacks below the 5-failures-in-10-minutes "
              "threshold are not detected.",
              "- Clock skew is detected only when a host's commands appear before the login that must precede them; a "
              "clock running ahead cannot be detected this way.",
              "- Host commands are linked to a login by user + host + time (inferred), because the system log has no session ID.",
              "- Mitigation results are a replay over recorded logs; an attacker who adapts is not modelled.", ""]
    return "\n".join(lines)
